package com.unispark.ecommerce.catalog.internal.persistence;

import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;

import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import com.unispark.ecommerce.catalog.ProductStatus;
import com.unispark.ecommerce.shared.Currency;
import com.unispark.ecommerce.shared.LocalizedText;
import com.unispark.ecommerce.shared.TenantScopedEntity;

/** Aggregate root: options, variants and images are created, changed and removed through the product. */
@Entity
@Table(name = "product")
public class Product extends TenantScopedEntity {

    @JdbcTypeCode(SqlTypes.JSON)
    @Column(nullable = false)
    private LocalizedText name;

    @JdbcTypeCode(SqlTypes.JSON)
    private LocalizedText description;

    @Column(nullable = false)
    private String slug;

    @Column(name = "category_id")
    private UUID categoryId;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private ProductStatus status;

    @Enumerated(EnumType.STRING)
    @Column(name = "price_currency", nullable = false)
    private Currency priceCurrency;

    /** Generated by the database from name and slug. */
    @Column(name = "search_text", insertable = false, updatable = false)
    private String searchText;

    @OneToMany(mappedBy = "product", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("position")
    private List<ProductOption> options = new ArrayList<>();

    @OneToMany(mappedBy = "product", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("position")
    private List<ProductVariant> variants = new ArrayList<>();

    @OneToMany(mappedBy = "product", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("sortOrder")
    private List<ProductImage> images = new ArrayList<>();

    protected Product() {
    }

    public Product(LocalizedText name, LocalizedText description, String slug, UUID categoryId,
            Currency priceCurrency) {
        update(name, description, slug, categoryId, priceCurrency);
        this.status = ProductStatus.DRAFT;
    }

    public void update(LocalizedText name, LocalizedText description, String slug, UUID categoryId,
            Currency priceCurrency) {
        this.name = name;
        this.description = description;
        this.slug = slug;
        this.categoryId = categoryId;
        this.priceCurrency = priceCurrency;
    }

    public LocalizedText getName() {
        return name;
    }

    public LocalizedText getDescription() {
        return description;
    }

    public String getSlug() {
        return slug;
    }

    public UUID getCategoryId() {
        return categoryId;
    }

    public ProductStatus getStatus() {
        return status;
    }

    public void setStatus(ProductStatus status) {
        this.status = status;
    }

    public Currency getPriceCurrency() {
        return priceCurrency;
    }

    public List<ProductOption> getOptions() {
        return options;
    }

    public List<ProductVariant> getVariants() {
        return variants;
    }

    public List<ProductImage> getImages() {
        return images;
    }
}
